/**
 * The sixteen pasta shapes a Cover is drawn from: eight from #46 and eight
 * more from #228, when a library of ninety recipes showed the same shape too
 * often.
 *
 * Each shape is authored in a `0 0 100 100` viewBox with absolute
 * coordinates and closed subpaths only — no strokes, no transforms — so a
 * Cover can be scaled and rotated freely without its line weights drifting.
 *
 * `body` is filled with the lighter tone of the Cover's dye; `detail`
 * carries ridges, grooves and cavities and is filled with the dye itself at
 * partial opacity. A shape must read from `body` alone — `detail` is
 * seasoning, never what makes it legible.
 *
 * Drawn by hand for Kamosu. No traced or third-party artwork, so there is no
 * licence obligation and nothing to vendor.
 */
export interface PastaShape {
	/** Stable key. Never renamed: it is what the Lineage id resolves to. */
	readonly key: string;
	/** The shape's Italian name, for tests and for people reading the code. */
	readonly name: string;
	readonly body: readonly string[];
	readonly detail: readonly string[];
}

